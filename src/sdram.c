static inline void sdram_fmc_config(void){
    FMC_Bank5_6_R->SDCR[0] = FMC_SDCRx_NC_0 | FMC_SDCRx_NR_1 | FMC_SDCRx_MWID_1 | FMC_SDCRx_NB | FMC_SDCRx_CAS | FMC_SDCRx_SDCLK_1 | FMC_SDCRx_RBURST | FMC_SDCRx_RPIPE_1;
    FMC_Bank5_6_R->SDTR[0] = FMC_SDTRx_TMRD_0 | FMC_SDTRx_TXSR_0 | FMC_SDTRx_TXSR_1 | FMC_SDTRx_TXSR_2 | FMC_SDTRx_TRAS_2 | FMC_SDTRx_TRC_0 | FMC_SDTRx_TRC_2 | FMC_SDTRx_TWR_0 | FMC_SDTRx_TRP_0 | FMC_SDTRx_TRCD_0;
    FMC_Bank1_R->BTCR[0] |= FMC_BCR1_FMCEN;
    FMC_Bank5_6_R->SDCMR = FMC_SDCMR_MODE_0 | FMC_SDCMR_CTB1;
    volatile uint32_t counter = 200U * 200U;
    while (counter > 0){
        counter--;
    }
    FMC_Bank5_6_R->SDCMR = FMC_SDCMR_MODE_1 | FMC_SDCMR_CTB1;
    FMC_Bank5_6_R->SDCMR = FMC_SDCMR_MODE_0 | FMC_SDCMR_MODE_1 | FMC_SDCMR_CTB1 | (7UL << FMC_SDCMR_NRFS_Pos);
    FMC_Bank5_6_R->SDCMR = FMC_SDCMR_MODE_2 | FMC_SDCMR_CTB1 | (0x230 << FMC_SDCMR_MRD_Pos);
    FMC_Bank5_6_R->SDRTR = (761UL << FMC_SDRTR_COUNT_Pos);
}

void sdram_setup(void){
    sdram_fmc_clock();
    sdram_gpio_mode();
    sdram_gpio_speed();
    sdram_gpio_alternate_function();
    sdram_fmc_config();
}
